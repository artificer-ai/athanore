# The HTTP reference: the snapshot, operation by operation
# --------------------------------------------------------------------------


def _schema_anchor(name: str) -> str:
    """The explicit id a schema's heading carries."""

    return f"schema-{name}"


def _type_of(schema: dict[str, Any] | None) -> str:
    """A JSON Schema rendered as a type name, with `$ref`s as links."""

    if not schema:
        return "`any`"
    if "$ref" in schema:
        name = str(schema["$ref"]).rsplit("/", 1)[-1]
        return f"[`{name}`](#{_schema_anchor(name)})"
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return " \\| ".join(_type_of(each) for each in schema[key])
    if "allOf" in schema:
        return " & ".join(_type_of(each) for each in schema["allOf"])
    if "const" in schema:
        return f"`{schema['const']!r}`"
    if "enum" in schema:
        return ", ".join(f"`{value!r}`" for value in schema["enum"])
    kind = schema.get("type")
    if kind == "array":
        return f"`array` of {_type_of(schema.get('items'))}"
    if kind == "object":
        extra = schema.get("additionalProperties")
        if isinstance(extra, dict):
            return f"`object` of {_type_of(extra)}"
        return "`object`"
    if kind is None:
        return "`any`"
    if isinstance(kind, list):
        return " \\| ".join(f"`{each}`" for each in kind)
    fmt = schema.get("format")
    return f"`{kind}`" + (f" ({fmt})" if fmt else "")


def _parameters(operation: dict[str, Any]) -> list[str]:
    """The path, query and header parameters, as one table."""

    params = operation.get("parameters") or []
    if not params:
        return []
    lines = [
        "**Parameters**",
        "",
        "| Parameter | In | Type | Required | Description |",
        "|---|---|---|---|---|",
    ]
    for param in params:
        required = "yes" if param.get("required") else "no"
        lines.append(
            f"| `{param['name']}` | {param['in']} | "
            f"{_type_of(param.get('schema'))} | {required} "
            f"| {_cell(param.get('description', ''))} |"
        )
    lines.append("")
    return lines


def _body(operation: dict[str, Any]) -> list[str]:
    """The request body, named by its schema."""

    body = operation.get("requestBody")
    if not body:
        return []
    lines: list[str] = []
    for media, entry in sorted(body.get("content", {}).items()):
        required = " (required)" if body.get("required") else ""
        lines.append(
            f"**Request body**{required} — `{media}`, {_type_of(entry.get('schema'))}"
        )
        lines.append("")
    return lines


def _responses(operation: dict[str, Any]) -> list[str]:
    """One row per declared status."""

    responses = operation.get("responses") or {}
    lines = [
        "**Responses**",
        "",
        "| Status | Body | Description |",
        "|---|---|---|",
    ]
    for status in sorted(responses, key=lambda value: (len(value), value)):
        response = responses[status]
        schema: dict[str, Any] | None = None
        for entry in response.get("content", {}).values():
            schema = entry.get("schema")
            break
        rendered = _type_of(schema) if schema is not None else "empty"
        lines.append(
            f"| `{status}` | {rendered} | {_cell(response.get('description', ''))} |"
        )
    lines.append("")
    return lines


def _operations(spec: dict[str, Any]) -> list[str]:
    """One `##` per tag, in the document's tag order, then its operations."""

    by_tag: dict[str, list[tuple[str, str, dict[str, Any]]]] = {}
    for path, item in spec["paths"].items():
        for method, operation in item.items():
            for tag in operation.get("tags") or ["untagged"]:
                by_tag.setdefault(tag, []).append((path, method.upper(), operation))

    declared = [tag["name"] for tag in spec.get("tags", [])]
    order = declared + sorted(set(by_tag) - set(declared))
    described = {
        tag["name"]: tag.get("description", "") for tag in spec.get("tags", [])
    }

    lines: list[str] = []
    for tag in order:
        entries = by_tag.get(tag)
        if not entries:
            continue
        lines += [f"## {tag}", ""]
        if described.get(tag):
            lines += [_prose(described[tag]), ""]
        for path, method, operation in sorted(entries):
            operation_id = operation.get("operationId", "")
            lines += [
                f"### `{method} {path}` {{#op-{operation_id}}}",
                "",
            ]
            if operation.get("summary"):
                lines += [_prose(operation["summary"]), ""]
            lines += [
                f"Credential: {reference.credential(operation)}. "
                f"Operation id: `{operation_id}`.",
                "",
            ]
            if operation.get("description"):
                lines += [_prose(operation["description"]), ""]
            lines += _parameters(operation)
            lines += _body(operation)
            lines += _responses(operation)
    return lines


def _schemas(spec: dict[str, Any]) -> list[str]:
    """Every entry of `components.schemas`, sorted, as a field table."""

    lines = ["## Schemas", ""]
    schemas: dict[str, Any] = spec.get("components", {}).get("schemas", {})
    for name in sorted(schemas):
        schema = schemas[name]
        lines += [f"### `{name}` {{#{_schema_anchor(name)}}}", ""]
        if schema.get("description"):
            lines += [_prose(schema["description"]), ""]
        if "enum" in schema:
            lines += [f"- `{value!r}`" for value in schema["enum"]]
            lines.append("")
            continue
        properties: dict[str, Any] = schema.get("properties") or {}
        if not properties:
            lines += [f"Type: {_type_of(schema)}", ""]
            continue
        required = set(schema.get("required") or ())
        lines += ["| Field | Type | Required | Description |", "|---|---|---|---|"]
        for field, entry in properties.items():
            mark = "yes" if field in required else "no"
            lines.append(
                f"| `{field}` | {_type_of(entry)} | {mark} "
                f"| {_cell(entry.get('description', ''))} |"
            )
        lines.append("")
    return lines


