#!/usr/bin/env python
"""Write the generated reference of the documentation site.

The site under `docs/site/` is for someone who has just installed
Athanore, and it restates no rule (D214). Every fact with a shape — a
default, a name, a signature, a field list, a status code, a wire shape —
is generated into `docs/site/src/reference/` by this script, from the
package and from the committed OpenAPI snapshot; every hand-written page
beside it is narrative and links here for the vocabulary.

The precedent is `scripts/dump_openapi.py`, end to end: this script
renders, `docs/site/src/reference/*.md` is committed,
`tests/test_docs_site.py` asserts the committed bytes are what this
writes, and CI's `contract` job regenerates and runs `git diff
--exit-code`.

The bodies come from `scripts/_reference.py`. What is here is the
framing (the marker, the title and the lede of each page, and no citation
of `docs/v1/`, which the site does not publish) plus the two renderings
that are built here alone: the detailed HTTP reference, which walks the
snapshot operation by operation and schema by schema, and the settings
table, which is built from the descriptions on the pydantic-settings
model. `scripts/gen_skills.py` republishes these pages, links rewritten,
into `skills/*/reference/`, so a skill carries the same page rather than
a second framing of the same facts.

Determinism is the same contract as there: declaration order where it is
contract, sorted everywhere else, and no timestamps, no version numbers
and no absolute paths. `root_path`'s default is the one place that could
have produced one, and it is written out in words for exactly that
reason.
"""

from __future__ import annotations

import re
from collections.abc import Callable
from pathlib import Path
from typing import Any

import _reference as reference
from pydantic.fields import FieldInfo

from athanore.settings import AthanoreSettings, Retention, _TomlSource

ROOT = Path(__file__).resolve().parent.parent

#: Where the generated pages go, checkout-relative.
REFERENCE = "docs/site/src/reference"

#: The first line of every file this writes. `tests/test_docs_site.py`
#: asserts it is there, and that no hand-written page carries it. It is
#: an HTML comment, so it never reaches the rendered site: "do not edit"
#: is a message for whoever opens the file, not for a reader.
MARKER = "<!-- Generated by scripts/gen_docs.py. Do not edit. -->"

#: A Sphinx cross-reference role, as it arrives in a docstring and
#: therefore in the OpenAPI snapshot. Markdown has no roles, so
#: `:class:`~athanore.events.names.EventName`` becomes `EventName`.
_ROLE = re.compile(r":[a-z]+:`([^`]+)`")

#: A markdown ATX heading, for :func:`_shift`.
_HEADING = re.compile(r"^(#{1,5}) ")

#: A dotted module path in front of a type name. `reference.type_name`
#: strips this package's own; a settings field annotated `SecretStr`
#: arrives as `pydantic.types.SecretStr`, and the module it is defined in
#: is not what an author writes.
_QUALIFIED = re.compile(r"\b(?:[A-Za-z_]\w*\.)+([A-Za-z_]\w*)")


#: One part of a parenthetical that is a citation of a design document:
#: its two-digit number, with or without a section, or a decision
#: number. The package's own docstrings carry them, so they arrive here
#: through every shared body and through the descriptions in the
#: snapshot. Exactly two digits, so `PluginError(400, ...)` keeps its
#: arguments.
_CITATION = re.compile(r"(?:\d{2}(?: §[^,;()]*)?|D\d+)")

#: A parenthetical, with the whitespace in front of it — a space, a
#: newline, or both, because a citation that opened a wrapped line would
#: otherwise leave the sentence's full stop stranded on one of its own.
#: Nested parentheses are deliberately not matched: a citation never
#: contains one.
_PARENTHETICAL = re.compile(r"( ?\n?)\(([^()]*)\)")


def _uncited(text: str) -> str:
    """``text`` with every citation of an unpublished document removed.

    The site does not publish the design documents, so `(05 §Agent
    classes)` points a reader at nothing. The sentence it hangs off
    always stands without it — the citation says where a rule is fixed,
    not what it is — so the parenthetical is dropped rather than turned
    into a broken link. A parenthetical that carries something else
    beside a citation keeps that something else.
    """

    def rebuild(match: re.Match[str]) -> str:
        parts = re.split(r"(, |; )", match.group(2))
        kept: list[str] = []
        for index in range(0, len(parts), 2):
            if _CITATION.fullmatch(parts[index].strip()):
                continue
            if kept:
                kept.append(parts[index - 1])
            kept.append(parts[index])
        if not kept:
            return ""
        return f"{match.group(1)}({''.join(kept)})"

    return _PARENTHETICAL.sub(rebuild, text)


def _page(title: str, lede: list[str], body: list[str]) -> str:
    """A title, an opening paragraph, and one generated body."""

    return reference.document(
        [title, "", *lede, "", *(_uncited(line) for line in body)], marker=MARKER
    )


def _shift(lines: list[str]) -> list[str]:
    """Every heading one level deeper.

    A body renderer opens at `##`, because it is normally the whole of a
    page. `plugins.md` carries two of them, so each is nested under a
    heading of its own and everything below it moves down with it. There
    are no fenced blocks in a generated body, so a leading `#` is always
    a heading.
    """

    return [_HEADING.sub(r"#\1 ", line) for line in lines]


def _prose(text: str) -> str:
    """A docstring as markdown: roles resolved, whitespace preserved.

    The descriptions in the snapshot are Python docstrings, so they carry
    Sphinx roles and dotted paths that mean nothing to a reader of the
    rendered page. Double backticks are left alone — they are a valid
    markdown code span already.
    """

    def name(match: re.Match[str]) -> str:
        target = match.group(1).lstrip("~").rsplit(".", 1)[-1]
        return f"`{target}`"

    return _uncited(_ROLE.sub(name, text)).strip()


def _cell(text: str) -> str:
    """One table cell: no newlines, and no pipe that would end it early."""

    return " ".join(_prose(text).split()).replace("|", "\\|")


def _annotation(field: FieldInfo) -> str:
    """A field's type, unqualified and safe inside a table cell.

    A union is spelled with `|`, which is also the column separator, so
    it is escaped here rather than in `reference.type_name` — the skills
    render the same names outside a table and want them unescaped.
    """

    text = _QUALIFIED.sub(r"\1", reference.type_name(field.annotation))
    return f"`{text}`".replace("|", "\\|")


