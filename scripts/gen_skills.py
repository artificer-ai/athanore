#!/usr/bin/env python
"""Write the generated reference of every skill under `skills/`.

A skill is a pointer, never a copy (D213): a `SKILL.md` is hand-written
and states no fact that is written down somewhere else, and every fact it
would otherwise have restated is generated here — the public API, the
node options, the agent attributes, the event vocabulary, the plugin
declarations and the context a handler is handed, the route table and the
command tree.

The precedent is `scripts/dump_openapi.py`, end to end: this script
renders, `skills/*/reference/*.md` is committed, `tests/test_skills.py`
asserts the committed bytes are what this renders, and CI's `contract`
job regenerates and runs `git diff --exit-code`.

Determinism is the whole point, as it is there. No timestamps, no version
numbers, no absolute paths, no ordering that can vary between runs: enum
members and dataclass fields keep declaration order, which is contract,
and everything else is sorted. Every file begins with :data:`MARKER` and
ends with a trailing newline.

`scripts/` is dev machinery rather than a package. Nothing in `athanore/`
imports this, and this starts no server, opens no database and reaches no
network — it imports the package, reads its own tree, and reads the
committed OpenAPI snapshot.
"""

