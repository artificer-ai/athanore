def _credential(operation: dict[str, Any]) -> str:
    """The security scheme an operation declares, as one word."""

    security = operation.get("security")
    if not security:
        return "none"
    return ", ".join(sorted(scheme for entry in security for scheme in entry))


def _routes() -> str:
    """One row per operation of the committed OpenAPI snapshot.

    Read from `tests/snapshots/openapi.json` rather than from
    `create_app()`, so that a stale snapshot fails one check — the
    OpenAPI one — instead of two, and so this script never builds an
    application.
    """

    snapshot = json.loads(
        (ROOT / "tests" / "snapshots" / "openapi.json").read_text(encoding="utf-8")
    )
    lines = [
        "# The route table",
        "",
        "Every operation of `tests/snapshots/openapi.json`, the wire contract",
        "of `docs/v1/08-api.md` §Endpoints, generated from the code. The",
        "credential column is what the operation declares:",
        "`docs/v1/08-api.md` §Authentication (12 has the model).",
        "",
        "| Method | Path | Tag | Operation | Credential | Summary |",
        "|---|---|---|---|---|---|",
    ]
    rows: list[tuple[str, str, str, str, str, str]] = []
    for path, item in snapshot["paths"].items():
        for method, operation in item.items():
            rows.append(
                (
                    path,
                    method.upper(),
                    ", ".join(operation.get("tags", ())),
                    operation.get("operationId", ""),
                    _credential(operation),
                    operation.get("summary", ""),
                )
            )
    for path, method, tags, operation_id, credential, summary in sorted(rows):
        lines.append(
            f"| `{method}` | `{path}` | {tags} | `{operation_id}` "
            f"| {credential} | {summary} |"
        )
    return _document(lines)


