def _parameter(parameter: Any) -> str | None:
    """One click parameter as a bullet, or ``None`` for a hidden one."""

    if getattr(parameter, "hidden", False):
        return None
    if parameter.param_type_name == "argument":
        label = parameter.metavar or str(parameter.name).upper()
        head = f"- `{label}`"
    else:
        head = "- " + ", ".join(f"`{opt}`" for opt in sorted(parameter.opts))
        if parameter.metavar:
            head += f" `{parameter.metavar}`"
    if parameter.required:
        head += " (required)"
    elif parameter.default is not None and parameter.default is not False:
        head += f" (default: `{parameter.default!r}`)"
    help_text = _first_line(getattr(parameter, "help", None))
    if help_text:
        head += f" — {help_text}"
    return head


def _command(command: Any, path: str, level: int) -> list[str]:
    """A heading, the help, the parameters, then every subcommand."""

    lines = [f"{'#' * level} `{path}`", ""]
    summary = _first_line(command.help or command.short_help)
    if summary:
        lines += [summary, ""]
    rendered = [
        bullet for bullet in map(_parameter, command.params) if bullet is not None
    ]
    if rendered:
        lines += [*rendered, ""]
    for name in sorted(getattr(command, "commands", {})):
        lines += _command(command.commands[name], f"{path} {name}", level + 1)
    return lines


def _commands() -> str:
    """The command tree, walked through click."""

    root: Any = get_command(cli_app)
    lines = [
        "# The command tree",
        "",
        "`athanore`, as `athanore/cli/__init__.py` and the verb modules",
        "beside it build it. What each verb is for is",
        "`docs/v1/11-cli.md` §Verbs; how a verb reaches a server is",
        "`docs/v1/11-cli.md` §Client connection; what it exits with is",
        "`docs/v1/11-cli.md` §Exit codes.",
        "",
        *_command(root, "athanore", 2),
    ]
    return _document(lines)


