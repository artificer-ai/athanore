def _event_groups() -> list[tuple[str, list[EventName]]]:
    """`EventName`'s members, grouped by the comment blocks of its source."""

    groups: list[tuple[str, list[EventName]]] = []
    for line in inspect.getsource(EventName).splitlines():
        stripped = line.strip()
        if stripped.startswith("# "):
            groups.append((stripped[2:].strip(), []))
        elif "=" in stripped:
            member = EventName.__members__.get(stripped.split("=", 1)[0].strip())
            if member is not None:
                if not groups:
                    groups.append(("Events", []))
                groups[-1][1].append(member)
    grouped = [(title, members) for title, members in groups if members]
    seen = {member for _, members in grouped for member in members}
    missing = [member.value for member in EventName if member not in seen]
    if missing:
        raise RuntimeError(
            f"athanore/events/names.py has members no comment block covers: "
            f"{missing}. Group them, or this reference would drop them silently."
        )
    return grouped


def _payload_fields(model: type[BaseModel]) -> str:
    """One payload's wire fields: ``key?: type``, in declaration order."""

    parts: list[str] = []
    for name, field in model.model_fields.items():
        key = field.serialization_alias or name
        mark = "" if field.is_required() else "?"
        parts.append(f"`{key}{mark}: {_type(field.annotation)}`")
    return ", ".join(parts) if parts else "no fields"


def _events() -> str:
    """The vocabulary, and the payload each name carries."""

    lines = [
        "# The event vocabulary",
        "",
        "Every member of `EventName` in `athanore/events/names.py`, with the",
        "fields of the payload it carries from `athanore/events/payloads.py`.",
        "The names are fixed by `docs/v1/03-domain-model.md` §Event",
        "vocabulary and the payloads by `docs/v1/18-event-payloads.md`",
        "§Payloads. A `?` marks a field that is absent rather than null when",
        "it has no value (`docs/v1/18-event-payloads.md` §Rules). The",
        "envelope these travel in — what it carries besides `data`, and",
        "which of those may be absent — is `docs/v1/18-event-payloads.md`",
        "§Envelope.",
        "",
    ]
    for title, members in _event_groups():
        lines += [f"## {title}", ""]
        for member in members:
            lines.append(f"- `{member.value}` — {_payload_fields(PAYLOADS[member])}")
        lines.append("")
    lines += [
        "## Published but never stored",
        "",
        "`EPHEMERAL` in `athanore/events/names.py`:",
        "",
    ]
    for name in sorted(member.value for member in EPHEMERAL):
        lines.append(f"- `{name}`")
    return _document(lines)


