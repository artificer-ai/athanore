def _public_api() -> str:
    """Every name `athanore` exports, resolved through its `__getattr__`."""

    lines = [
        "# The public API",
        "",
        "Every name in `athanore.__all__`, read off `athanore/__init__.py`.",
        "The surface is fixed by",
        "`docs/v1/02-architecture.md` §Public API (`athanore/__init__.py`).",
        "The deprecated MVP aliases are not in `__all__`, and are not listed",
        "here.",
        "",
    ]
    for name in sorted(athanore.__all__):
        value = getattr(athanore, name)
        if inspect.isclass(value):
            kind = "class"
        elif inspect.isroutine(value):
            kind = "function"
        else:
            kind = type(value).__name__
        where = _relative(value) or "athanore/__init__.py"
        lines.append(f"- **`{name}`** — {kind}, `{where}`")
        signature = _signature(value)
        if signature is not None:
            lines.append(f"  - `{name}{signature}`")
        summary = _summary(value)
        if summary:
            lines.append(f"  - {summary}")
    return _document(lines)


def _node_options() -> str:
    """The metadata seam: `wf.node()`'s keywords, and `Pool`'s fields."""

    lines = [
        "# Node options and pools",
        "",
        "The keyword parameters of `Workflow.node()` in `athanore/workflow.py`,",
        "which is the metadata seam of",
        "`docs/v1/04-engine.md` §Node options (metadata seam), and the fields",
        "of `Pool` in `athanore/engine/pools.py` (`docs/v1/04-engine.md` §Pools).",
        "",
        "## `@wf.node(...)`",
        "",
    ]
    for name, parameter in inspect.signature(Workflow.node).parameters.items():
        if name == "self" or parameter.kind is inspect.Parameter.VAR_KEYWORD:
            continue
        if parameter.kind is inspect.Parameter.KEYWORD_ONLY:
            lines.append(
                _declaration(
                    name, _type(parameter.annotation), _default(parameter.default)
                )
            )
    lines += ["", "## `Pool`", ""]
    for name, annotation, default in _dataclass_fields(Pool):
        lines.append(_declaration(name, annotation, default))
    return _document(lines)


